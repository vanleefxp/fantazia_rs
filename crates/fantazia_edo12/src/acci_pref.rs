            let tone = OTone::new(tone_value).unwrap();
            let expected_sharp = sharp[tone_value as usize];
            let expected_flat = flat[tone_value as usize];
            assert_eq!(tone.to_opitch(AcciPref::ALL_SHARP), expected_sharp);
