#[cfg(feature = "macro")]
impl ToTokens for OStep {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        const OSTEP_IDENTS: [char; 7] = ['C', 'D', 'E', 'F', 'G', 'A', 'B'];
        let ident = OSTEP_IDENTS[*self as usize];
        tokens.extend(quote! {
            ::fantazia::edo12::step::OStep::#ident
        });
    }
}

#[cfg(feature = "macro")]
impl ToTokens for Step {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        let value = self.0;
        tokens.extend(quote! {
            ::fantazia::edo12::step::Step::new(#value)
        });
    }
}
